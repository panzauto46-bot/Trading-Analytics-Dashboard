// Helper function to get trading statistics
export const getTradingStats = () => {
  const totalTrades = tradingHistory.length;
  const winningTrades = tradingHistory.filter(t => t.pnl > 0).length;
  const losingTrades = tradingHistory.filter(t => t.pnl < 0).length;
  const totalPnL = tradingHistory.reduce((sum, t) => sum + t.pnl, 0);
  const totalFees = tradingHistory.reduce((sum, t) => sum + t.fee, 0);
  const netPnL = totalPnL + totalFees;
  const winRate = (winningTrades / totalTrades) * 100;
  const avgWin = tradingHistory.filter(t => t.pnl > 0).reduce((sum, t) => sum + t.pnl, 0) / winningTrades;
  const avgLoss = tradingHistory.filter(t => t.pnl < 0).reduce((sum, t) => sum + t.pnl, 0) / losingTrades;
  const profitFactor = Math.abs(tradingHistory.filter(t => t.pnl > 0).reduce((sum, t) => sum + t.pnl, 0) / 
                                tradingHistory.filter(t => t.pnl < 0).reduce((sum, t) => sum + t.pnl, 0));

  return {
    totalTrades,
    winningTrades,
    losingTrades,
    totalPnL,
    totalFees,
    netPnL,
    winRate,
    avgWin,
    avgLoss,
    profitFactor
  };
};

// Helper function to get trades by symbol
export const getTradesBySymbol = (symbol: string) => {
  return tradingHistory.filter(t => t.symbol === symbol);
};

// Helper function to get unique symbols
export const getUniqueSymbols = () => {
  return [...new Set(tradingHistory.map(t => t.symbol))];
};
